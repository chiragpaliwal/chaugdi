import { defineConfig, type Plugin } from 'vitest/config';
import react from '@vitejs/plugin-react';

const PUBLIC_FILES = ['/manifest.webmanifest', '/icons/icon.svg', '/icons/icon-180.png', '/icons/icon-192.png', '/icons/icon-512.png'];

/**
 * Offline shell (GDD §13): emits sw.js with every built file precached, so solo mode
 * works in airplane mode after the first load. A new build changes the cache name.
 */
function serviceWorker(): Plugin {
  return {
    name: 'chaugadi-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = ['/', ...PUBLIC_FILES, ...Object.keys(bundle).filter((f) => !f.endsWith('.map')).map((f) => `/${f}`)];
      const version = Object.keys(bundle).sort().join('|');
      let hash = 0;
      for (let i = 0; i < version.length; i++) hash = (Math.imul(31, hash) + version.charCodeAt(i)) | 0;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(`chaugadi-${(hash >>> 0).toString(36)}`, files) });
    },
  };
}

const swSource = (cache: string, files: string[]) => `// Generated by vite.config.ts
const CACHE = ${JSON.stringify(cache)};
const PRECACHE = ${JSON.stringify(files)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/') || url.pathname.startsWith('/parties/')) return;
  if (req.mode === 'navigate') {
    // Network first so a new build arrives; the cached shell serves every route offline.
    e.respondWith(fetch(req).catch(() => caches.match('/', { cacheName: CACHE })));
    return;
  }
  e.respondWith(caches.match(req, { cacheName: CACHE }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  })));
});
`;

export default defineConfig({
  plugins: [react(), serviceWorker()],
  server: { port: 5173, strictPort: true },
  test: { include: ['src/**/*.test.ts'] },
});
